import assert from 'node:assert/strict';
import {generateKeyPairSync,randomUUID,sign,createPublicKey} from 'node:crypto';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {test} from 'node:test';
import {createLeaseIssuer,encodeMachine,InstallationStore} from '../../packages/registration/src/index.ts';
import {venueServiceFixture,set,read} from '../../packages/registration/test/fixtures/venue-service.ts';
import {RemoteAccessStore} from '../../packages/remote-access/src/placement.ts';
import {verifyManifest} from '../../packages/remote-access/src/manifest.ts';
import {bootstrapTestCloud} from './bootstrap.mjs';
import {openTestRemoteRuntime} from './remote-runtime.mjs';
import {executeTestServiceCommand} from './service-controls.mjs';
const mode='test-venue-levels',origin='https://cloud.example.test';
const environment={CLOUD_VENUE_SERVICE_LEVELS:'test',CLOUD_TEST_SERVICE_PLANS:'0'};

// Clearing the peer config would trigger box reprovisioning; leaving setup active would retain the gateway route.
test('remote switch withdraws signed routes after restart and restores the same peer without changing backups',async t=>{
 const f=await venueServiceFixture();t.after(()=>f.close());
 const directory=await mkdtemp(join(tmpdir(),'test-remote-switch-'));t.after(()=>rm(directory,{recursive:true,force:true}));
 await bootstrapTestCloud(directory);
 for(const venue of f.venues)await set(f,'connected',venue);
 const current=(await f.pool.query('SELECT id FROM installations WHERE venue_id=ANY($1::uuid[]) AND superseded_by IS NULL ORDER BY venue_id',[f.venues])).rows.map(r=>r.id);
 const installationId=current[0],keys=generateKeyPairSync('ed25519');
 await f.pool.query('UPDATE installations SET public_key=$2 WHERE id=$1',[installationId,keys.publicKey.export({format:'der',type:'spki'}).toString('base64url')]);
 const issuer=createLeaseIssuer(generateKeyPairSync('ed25519').privateKey.export({format:'der',type:'pkcs8'}).toString('base64url'));
 let lease;
 const proof=(action)=>{const payload=encodeMachine({origin,installationId,operationId:randomUUID(),issuedAt:Date.now(),action,body:'{}',lease:lease?JSON.stringify(lease):''});return {payload:payload.toString('base64url'),signature:sign(null,payload,keys.privateKey).toString('base64url')};};
 const installations=new InstallationStore(f.pool,issuer,origin,undefined,mode);
 lease=(await installations.execute('renew',proof('renew'))).lease;
 const options={pool:f.pool,directory,mode},runtime=await openTestRemoteRuntime(options),remote=new RemoteAccessStore(f.pool,mode);
 const peer=()=>generateKeyPairSync('x25519').publicKey.export({format:'der',type:'spki'}).subarray(-32).toString('base64');
 const placement=await remote.provision(installationId,runtime.cellId,peer());await remote.provision(current[1],runtime.cellId,peer());
 const trust=createPublicKey(await readFile(join(directory,'gateway-issuer.pem')));
 const manifest=async()=>verifyManifest(JSON.parse(await readFile(join(directory,'gateway-manifest.json'),'utf8')),trust,runtime.cellId);
 async function drain(worker){await worker.schedule();for(let n=0;n<12&&await worker.runOnce();n++);}
 await drain(runtime.worker);assert.deepEqual((await manifest()).routes.map(r=>r.installationId).sort(),[...current].sort());
 const context={pool:f.pool,issuer,origin,environment,directory},command={command:'remote-access',installationId};
 const before=await installations.execute('configuration',proof('configuration'));
 assert.deepEqual(await executeTestServiceCommand(context,{...command,enabled:false}),{enabled:false});
 const off=await installations.execute('configuration',proof('configuration'));
 assert.equal(off.revision,before.revision+1);
 const setup=view=>view.services.find(s=>s.service==='remote_access');
 assert.equal(setup(off).state,'unconfigured');assert.deepEqual(setup(off).configuration,setup(before).configuration,'ordinary box refresh must still see its current peer key');
 const backups=view=>view.services.filter(s=>['continuous_backup','retained_snapshots'].includes(s.service));
 assert.deepEqual(backups(off),backups(before));assert.equal((await read(f)).level,'connected');
 await drain(runtime.worker);assert.deepEqual((await manifest()).routes.map(r=>r.installationId),[current[1]],'the running worker must withdraw the route before restart');
 const restarted=await openTestRemoteRuntime(options);await drain(restarted.worker);
 assert.deepEqual((await manifest()).routes.map(r=>r.installationId),[current[1]]);
 await assert.rejects(remote.authorizeCertificate(installationId,'public','unused'),/permission_denied/);
 assert.deepEqual(await executeTestServiceCommand(context,{...command,enabled:false}),{enabled:false});
 assert.equal((await installations.execute('configuration',proof('configuration'))).revision,off.revision,'repeated off must not invalidate configuration again');
 assert.deepEqual(await executeTestServiceCommand(context,{...command,enabled:true}),{enabled:true});
 const on=await installations.execute('configuration',proof('configuration'));
 assert.equal(on.revision,off.revision+1);assert.equal(setup(on).state,'provisioning');assert.deepEqual(setup(on).configuration,setup(before).configuration);assert.deepEqual(backups(on),backups(before));
 await drain(restarted.worker);assert.deepEqual((await manifest()).routes.map(r=>r.installationId).sort(),[...current].sort());
 assert.deepEqual((await remote.manifest(runtime.cellId)).routes.find(r=>r.installationId===installationId).peerPublicKey,placement.peerPublicKey);
 await executeTestServiceCommand(context,{...command,enabled:true});
 assert.equal((await installations.execute('configuration',proof('configuration'))).revision,on.revision,'repeated on preserves setup');
 const production=(await f.pool.query('SELECT id FROM installations WHERE venue_id=$1 AND superseded_by IS NULL',[f.production])).rows[0].id;
 const retired=(await f.pool.query('SELECT id FROM installations WHERE venue_id=$1 AND superseded_by IS NOT NULL',[f.venues[0]])).rows[0].id;
 for(const id of [production,retired])await assert.rejects(executeTestServiceCommand(context,{...command,installationId:id,enabled:false}),/test_cloud.service_target/);
 await f.pool.query('UPDATE installations SET revoked_at=clock_timestamp() WHERE id=$1',[installationId]);
 await assert.rejects(executeTestServiceCommand(context,{...command,enabled:false}),/test_cloud.service_target/);
 await assert.rejects(executeTestServiceCommand({...context,environment:{}},{...command,enabled:false}),/test_cloud.service_mode/);
});
