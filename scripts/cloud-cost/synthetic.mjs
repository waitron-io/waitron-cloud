import { priceUsage } from './model.mjs';

const fail = () => { throw Error('Invalid cloud cost live plan'); };
const need = value => { if (!value) fail(); };
const dimensions = ['s3Attempts', 'kmsAttempts', 'peakBytes', 'versions', 'elapsedSeconds'];
const hardCaps = { s3Attempts: 10000, kmsAttempts: 10000, peakBytes: 1073741824, versions: 1000, elapsedSeconds: 86400 };
const budgets = new WeakMap();
const number = value => need(typeof value === 'number' && Number.isFinite(value) && value >= 0 && value <= Number.MAX_SAFE_INTEGER);
const count = value => { number(value); need(Number.isSafeInteger(value)); };
const exact = (value, keys) => need(value && !Array.isArray(value)
  && Reflect.ownKeys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key)));
const date = value => { need(typeof value === 'string' && Number.isFinite(Date.parse(value))
  && new Date(value).toISOString() === value); return Date.parse(value); };

// A JSON planning envelope cannot carry payloads or executable property accessors.
function plain(value, ancestors = new Set(), budget = { left: 20000 }) {
  need(--budget.left >= 0 && ancestors.size < 24);
  if (value === null || ['string', 'boolean'].includes(typeof value)) return;
  if (typeof value === 'number') { number(value); return; }
  need(value && typeof value === 'object' && !ancestors.has(value));
  const array = Array.isArray(value), keys = Reflect.ownKeys(value);
  need(Object.getPrototypeOf(value) === (array ? Array.prototype : Object.prototype));
  if (array) need(value.length <= 10000 && keys.length === value.length + 1
    && keys.every(key => key === 'length' || typeof key === 'string' && /^(0|[1-9][0-9]*)$/.test(key) && Number(key) < value.length));
  ancestors.add(value);
  for (const key of keys) { const d = Object.getOwnPropertyDescriptor(value, key);
    need(typeof key === 'string' && Object.hasOwn(d, 'value')); plain(d.value, ancestors, budget); }
  ancestors.delete(value);
}

// This is a conservative planning check, not synthetic provenance or authority
// to create resources. A live runner must separately verify its generated bytes.
export function preflightLive(input) {
  try {
    plain(input); exact(input, ['manifest', 'rates', 'credits', 'window', 'contingencies', 'caps']);
    exact(input.window, ['startedAt', 'remainingSeconds', 'storageMonthSeconds']);
    const start = date(input.window.startedAt);
    number(input.window.remainingSeconds); number(input.window.storageMonthSeconds); need(input.window.storageMonthSeconds > 0);
    exact(input.contingencies, ['delayedCleanupSeconds', 'cancelledDeletionSeconds']);
    number(input.contingencies.delayedCleanupSeconds); number(input.contingencies.cancelledDeletionSeconds);
    need(input.contingencies.delayedCleanupSeconds > 0);
    need(input.caps && typeof input.caps === 'object' && !Array.isArray(input.caps));
    need(Object.keys(input.caps).every(key => dimensions.includes(key)));
    const caps = Object.fromEntries(dimensions.map(key => {
      const value = Object.hasOwn(input.caps, key) ? input.caps[key] : hardCaps[key];
      count(value); need(value > 0 && value <= hardCaps[key]); return [key, value];
    }));
    const rateIds = ['s3Put', 's3Get', 's3List', 's3Delete', 's3Control', 'kmsRequests', 'kmsKeyHours', 's3Storage', 'costExplorer'];
    exact(input.rates, rateIds);
    if (input.credits !== null) {
      exact(input.credits, ['availableUsd', 'applicable', 'observedAt', 'expiresAt']);
      if (input.credits.availableUsd !== null) number(input.credits.availableUsd);
      need(typeof input.credits.applicable === 'boolean'); date(input.credits.observedAt); date(input.credits.expiresAt);
    }
    const gaps = [], costs = {}, cleanup = { s3Attempts: 0, kmsAttempts: 0, elapsedSeconds: input.contingencies.delayedCleanupSeconds };
    let totals = null, grossUpperUsd = null, cashExposureUsd = null;
    if (input.manifest === null) gaps.push('shape:missing');
    else {
      const m = input.manifest;
      exact(m, ['schemaVersion', 'kind', 'region', 'gaps', 'bounds']);
      need(m.schemaVersion === 1 && m.kind === 'anonymous-storage-plan' && m.region === 'eu-north-1');
      need(Array.isArray(m.gaps) && new Set(m.gaps).size === m.gaps.length);
      for (const gap of m.gaps) {
        need(['daily-cadence', 'scheduled-boundaries', 'object-size-lifetimes', 'retry-ceilings', 'operation-billing'].includes(gap));
        gaps.push('shape:' + gap);
      }
      const b = m.bounds;
      exact(b, [...dimensions, 'unfinishedMultipart', 'activeKeySeconds', 'byteSeconds']);
      for (const key of ['s3Attempts', 'kmsAttempts', 'peakBytes', 'versions', 'unfinishedMultipart']) count(b[key]);
      for (const key of ['elapsedSeconds', 'activeKeySeconds', 'byteSeconds']) number(b[key]);
      need(b.unfinishedMultipart <= b.versions && b.activeKeySeconds >= b.elapsedSeconds && b.elapsedSeconds >= 900);
      // The planned cleanup uses 1000-entry version batches and one abort per
      // open upload; empty enumeration and final absence checks still issue calls.
      cleanup.s3Attempts = Math.max(1, Math.ceil(b.versions / 1000)) + Math.ceil(b.versions / 1000)
        + Math.max(1, Math.ceil(b.unfinishedMultipart / 1000)) + b.unfinishedMultipart + 4;
      cleanup.kmsAttempts = 2;
      totals = Object.fromEntries(dimensions.map(key => [key, b[key] + (cleanup[key] ?? 0)]));
      for (const key of dimensions) { number(totals[key]); if (totals[key] > caps[key]) gaps.push('cap:' + key); }
      if (totals.elapsedSeconds > input.window.remainingSeconds) gaps.push('foreground:insufficient-time');
      const quantity = (id, value, unit) => ({ id, value, unit, status: 'assumed', source: 'assumption:workload-assumption',
        scope: 'usage', region: m.region, observedAt: null, effectiveAt: null,
        bounds: { low: value, base: value, high: value, assumption: 'workload-assumption' }, reason: 'workload-assumption' });
      function price(id, value, unit) {
        const q = quantity('live-' + id.toLowerCase(), value, unit);
        const result = priceUsage(unit === 'byte-seconds'
          ? { input: q, period: quantity('storage-period', input.window.storageMonthSeconds, 'seconds') } : q, input.rates[id]);
        if (result.cost === null) gaps.push('rate:' + id);
        return result.cost;
      }
      // Separate request classes can each consume their expensive tier before
      // any volume discount. Bound every attempt by the largest marginal rate,
      // including per-attempt minimums and rounding, after all classes validate.
      const s3 = ['s3Put', 's3Get', 's3List', 's3Delete', 's3Control'].map(id => price(id, totals.s3Attempts, 'Requests'));
      costs.s3Requests = s3.includes(null) ? null : totals.s3Attempts * Math.max(...['s3Put', 's3Get', 's3List', 's3Delete', 's3Control'].map(id => {
        const rates = input.rates[id], first = rates.toSorted((a, b) => a.tier.begin - b.tier.begin)[0];
        let billed = Math.max(1, first.minimum.quantity);
        if (first.rounding.mode === 'ceil') billed = Math.ceil(billed / first.rounding.quantum) * first.rounding.quantum;
        return billed * Math.max(...rates.map(rate => rate.value));
      }));
      costs.kmsRequests = price('kmsRequests', totals.kmsAttempts, 'Requests');
      const keySeconds = b.activeKeySeconds + input.contingencies.delayedCleanupSeconds + input.contingencies.cancelledDeletionSeconds;
      number(keySeconds);
      costs.keyHours = price('kmsKeyHours', keySeconds / 3600, 'hours');
      const byteSeconds = Math.max(b.byteSeconds, b.peakBytes * totals.elapsedSeconds); number(byteSeconds);
      costs.storage = price('s3Storage', byteSeconds, 'byte-seconds');
      costs.billing = price('costExplorer', 3, 'Requests');
      if (!Object.values(costs).includes(null)) { grossUpperUsd = Object.values(costs).reduce((sum, v) => sum + v, 0); number(grossUpperUsd); }
      if (input.credits !== null && date(input.credits.expiresAt) < start + keySeconds * 1000) gaps.push('credits:expiry');
    }
    const c = input.credits;
    if (c === null || c.availableUsd === null || !c.applicable) gaps.push('credits:unknown');
    else {
      if (date(c.observedAt) > start || date(c.expiresAt) <= start) gaps.push('credits:expiry');
      if (grossUpperUsd !== null && !gaps.includes('credits:expiry')) { cashExposureUsd = Math.max(0, grossUpperUsd - c.availableUsd);
        if (cashExposureUsd > 0) gaps.push('credits:insufficient'); }
    }
    const result = { preflightPassed: gaps.length === 0, providerAuthorised: false, caps, totals, cleanup, costs,
      grossUpperUsd, cashExposureUsd, billingCalls: 3, needsCreditDecision: gaps.some(gap => gap.startsWith('credits:')), gaps };
    budgets.set(result, { serialised: JSON.stringify(result), totals: structuredClone(totals), cleanup: structuredClone(cleanup) });
    return result;
  } catch { fail(); }
}

// Charge before dispatch, including failed attempts; reservations are never
// released on an unverified deletion. This guard cannot itself call a provider.
export function createLiveBudgetGuard(budget, { clock = () => performance.now() / 1000 } = {}) {
  try {
    const approved = budgets.get(budget);
    need(approved && !approved.claimed && budget.preflightPassed && approved.serialised === JSON.stringify(budget));
    const started = clock(); number(started); approved.claimed = true;
    const used = Object.fromEntries(dimensions.map(key => [key, 0]));
    return {
      admit(action) {
        try {
          plain(action); exact(action, dimensions);
          const now = clock(); number(now); need(now >= started);
          const next = Object.fromEntries(dimensions.map(key => {
            number(action[key]); if (key !== 'elapsedSeconds') count(action[key]);
            const value = key === 'elapsedSeconds' ? Math.max(used[key] + action[key], now - started) : used[key] + action[key]; number(value);
            need(value + (approved.cleanup[key] ?? 0) <= approved.totals[key]);
            return [key, value];
          }));
          Object.assign(used, next);
        } catch { fail(); }
      },
      snapshot() { return { ...used }; },
    };
  } catch { fail(); }
}
